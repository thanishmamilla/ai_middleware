import os
import time
import asyncio
import logging
from typing import List, Dict, Any, Tuple
from fastapi import HTTPException, status
from app.core.config import settings
from app.router.circuit_breaker import circuit_breaker

logger = logging.getLogger("FallbackRouter")

# Check if litellm is available
try:
    import litellm
    LITELLM_AVAILABLE = True
except ImportError:
    LITELLM_AVAILABLE = False

class FallbackRouter:
    def __init__(self):
        self.fallback_chains = settings.MODEL_FALLBACK_CHAINS

    def resolve_chain(self, requested_model: str) -> List[str]:
        return self.fallback_chains.get(requested_model, [requested_model])

    async def execute_call(
        self,
        requested_model: str,
        messages: List[Dict[str, str]],
        temperature: float = 0.7,
        stream: bool = False
    ) -> Tuple[Any, str, bool]:
        """
        Executes model completion across the fallback chain, respecting the Circuit Breaker.
        Returns: (response, model_executed, fallback_occurred)
        """
        chain = self.resolve_chain(requested_model)
        last_error = None
        fallback_occurred = False

        for idx, model_name in enumerate(chain):
            # Check circuit breaker
            if not circuit_breaker.can_execute(model_name):
                logger.warning(f"Circuit Breaker for '{model_name}' is OPEN. Skipping to fallback.")
                fallback_occurred = True
                continue

            try:
                logger.info(f"Executing call: model='{model_name}' (Target {idx + 1}/{len(chain)})")
                
                # Check for API keys or mock fallback mode
                # If neither OPENAI_API_KEY nor ANTHROPIC_API_KEY is set, provide a responsive mock
                has_keys = bool(os.environ.get("OPENAI_API_KEY") or os.environ.get("ANTHROPIC_API_KEY") or os.environ.get("GEMINI_API_KEY"))
                
                if not has_keys or not LITELLM_AVAILABLE:
                    # Deterministic simulated provider response for out-of-the-box local testing
                    await asyncio.sleep(0.08)
                    if "fail" in model_name.lower():
                        raise ConnectionError(f"Simulated connection failure for provider '{model_name}'")
                    
                    response = {
                        "id": f"chatcmpl-{int(time.time()*1000)}",
                        "object": "chat.completion",
                        "created": int(time.time()),
                        "model": model_name,
                        "choices": [
                            {
                                "index": 0,
                                "message": {
                                    "role": "assistant",
                                    "content": f"Response generated by Gateway via provider '{model_name}'. Answer: Successfully processed your request."
                                },
                                "finish_reason": "stop"
                            }
                        ],
                        "usage": {
                            "prompt_tokens": sum(len(m["content"].split()) for m in messages),
                            "completion_tokens": 15,
                            "total_tokens": sum(len(m["content"].split()) for m in messages) + 15
                        }
                    }
                else:
                    response = await asyncio.wait_for(
                        litellm.acompletion(
                            model=model_name,
                            messages=messages,
                            temperature=temperature,
                            stream=stream
                        ),
                        timeout=settings.PROVIDER_TIMEOUT_SEC
                    )

                # Record success on circuit breaker
                circuit_breaker.record_success(model_name)
                return response, model_name, fallback_occurred

            except Exception as e:
                logger.error(f"Provider '{model_name}' failed: {str(e)}")
                circuit_breaker.record_failure(model_name)
                last_error = e
                fallback_occurred = True
                continue

        # If all fallback targets fail
        raise HTTPException(
            status_code=status.HTTP_503_SERVICE_UNAVAILABLE,
            detail=f"All upstream models in fallback chain {chain} failed. Last error: {str(last_error)}"
        )

fallback_router = FallbackRouter()

